package com.flora.honey;

/**
 * 预测模型接口：蜜糖加密中“LLM 预测”的抽象，且由密钥播种（key-seeded）。
 *
 * <p>核心设计（用户指定）：解密时统一用“输入密钥”作为种子交给模型进行预测，
 * 再据此解码算术编码流。因此正确与错误密钥走的是<b>同一条路径</b>，
 * 区别只在于模型被不同密钥播种后给出的分布不同：
 * <ul>
 *   <li>正确密钥 → 分布与编码时一致 → 精确还原真实明文；</li>
 *   <li>错误密钥 → 分布不同，且输入的算术流是随机字节 → 解码出一段“看起来正常”的诱饵。</li>
 * </ul>
 * 由于不校验任何认证标签（tag），攻击者无法判断某次解密是否“正确”，从而避免提供预言机。</p>
 *
 * <p><b>上下文窗口：</b>模型可实现为条件模型——{@link #freq(int)} 返回的是
 * “在最近已观察到的若干 token（上下文窗口）条件下”的频率。编码器在编完一个 token 后调用
 * {@link #observe(int)} 推进窗口，解码器在解出一个 token 后调用同一方法。正确密钥下两端观察到
 * 的 token 序列一致，模型状态逐步同步 → 精确往返；错误密钥下窗口从某点分叉，但仍是自洽诱饵。</p>
 *
 * <p>原型用 {@link NgramTokenModel}（字符级、阶-N n-gram、由密钥播种）作为自包含占位；
 * 真实部署时换成 LLM 后端提供条件频率即可，接口不变。</p>
 */
public interface TokenModel {

    /** 词表大小（token id 取值范围 [0, vocabSize)）。 */
    int vocabSize();

    /**
     * 用输入密钥派生的种子初始化模型：重置回退先验并清空上下文窗口。
     * 之后 {@link #freq(int)} 返回该密钥（及其窗口）下的分布。
     */
    void seed(byte[] keySeed);

    /**
     * 返回当前密钥播种、当前上下文窗口下 token id 的相对频率（恒 &gt; 0），
     * 作为算术编码的概率分布。实现必须保证任意 id 的频率都 &ge; 1，
     * 使错误密钥解出的任意诱饵 token 都可能出现。
     */
    int freq(int id);

    /**
     * 用刚编码/解码出的 token 推进上下文窗口。编码端与解码端必须以相同顺序调用，
     * 保证正确密钥下两端模型状态一致。无上下文（order-0）的实现可为空操作。
     */
    void observe(int id);

    /** token id 对应的字符。 */
    char token(int id);

    /** 字符对应的 token id；超出词表范围时返回 0（占位，不影响原型演示）。 */
    int toId(char c);
}
