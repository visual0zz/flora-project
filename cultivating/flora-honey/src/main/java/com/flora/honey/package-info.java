/**
 * 蜜糖加密（Honey Encryption）演示工程。
 *
 * <p>核心性质：密文在正确密钥下还原真实明文；在任意错误密钥下不会报错，
 * 而是确定性地生成一段“看起来正常的文本”（诱饵），让截获者/审查者无法判断
 * 哪个密钥才是“对的”。</p>
 *
 * <p>设计要点（避免提供预言机）：
 * <ul>
 *   <li><b>统一解密路径</b>：正确与错误密钥都走“AES-CTR 解密 → 用密钥播种的模型做区间解码 → 文本”，
 *       不分支、不抛异常；</li>
 *   <li><b>密文无 tag</b>：不使用 GCM 之类带认证标签的算法，否则校验失败即可判定密钥对错；</li>
 *   <li><b>模型由密钥播种</b>：加密与解密都用输入密钥派生种子初始化同一预测模型，
 *       正确密钥下分布与编码时一致 → 精确还原，错误密钥下分布不同 → 不同诱饵。</li>
 * </ul>
 *
 * <p>本工程仅依赖 JDK 标准库实现演示。预测模型用 {@link NgramTokenModel} 占位
 * （字符级、阶-N n-gram 上下文窗口、由密钥播种）；真实部署可换成 LLM 后端
 * （如 Python/Ollama 提供条件频率），接口 {@link TokenModel} 不变，整体架构不变。</p>
 */
